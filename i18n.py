# Langue courante (mutable, modifiable à tout moment via set_lang)
# Défaut : anglais (le programme est partagé sans wallets ; la passphrase
# et le mot de passe maître restent toujours en anglais, quelle que soit
# la langue choisie dans le menu).
LANG = "en"


def load_lang():
    """Charge la langue depuis lang.txt (défaut 'fr')."""
    global LANG
    try:
        if LANG_FILE.exists():
            code = LANG_FILE.read_text(encoding="utf-8").strip()
            if code in LANGS:
                LANG = code
    except Exception:
        pass
    return LANG


def save_lang(code: str):
    """Persiste la langue dans lang.txt."""
    try:
        LANG_FILE.write_text(code, encoding="utf-8")
    except Exception:
        pass


def set_lang(code: str):
    """Définit la langue courante (si connue) et la persiste."""
    global LANG
    if code not in LANGS:
        return False
    LANG = code
    save_lang(code)
    return True


def get_lang():
    return LANG


def t(key: str, **kwargs):
    """Renvoie la chaîne traduite pour la langue courante.
    Si la langue est RTL (ar, he), le texte est visuellement réarrangé
    par l'algorithme BiDi avant d'être renvoyé, pour un affichage correct
    même dans un terminal ne gérant pas nativement le bidirectionnel.
    Fallback : français, puis la clé brute.
    """
    tmpl = STRINGS.get(LANG, {}).get(key)
    if tmpl is None:
        # Les langues nouvellement proposées restent entièrement lisibles
        # grâce au fallback anglais jusqu'à leur traduction complète.
        tmpl = STRINGS.get("en", {}).get(key)
    if tmpl is None:
        tmpl = STRINGS["fr"].get(key, key)
    if kwargs:
        try:
            tmpl = tmpl.format(**kwargs)
        except (KeyError, IndexError):
            pass
    if LANG in RTL_LANGS:
        tmpl = get_display(tmpl)
    return tmpl


def t_en(key: str, **kwargs):
    """Renvoie la chaîne EN ANGLAIS quelle que soit la langue courante.
    Utilisé pour la passphrase du fichier wallet et le mot de passe maître,
    qui doivent rester en anglais même si l'utilisateur choisit une autre
    langue dans le menu principal."""
    tmpl = STRINGS.get("en", {}).get(key)
    if tmpl is None:
        tmpl = STRINGS["fr"].get(key, key)
    if kwargs:
        try:
            return tmpl.format(**kwargs)
        except (KeyError, IndexError):
            return tmpl
    return tmpl


